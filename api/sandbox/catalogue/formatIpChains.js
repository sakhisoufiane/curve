function combineChildComposers(chain) {
    chain.children.map((child) => {
        if (child.type === 'Composer' && child.children.length > 0) {
            chain.children = chain.children.concat(child.children);
            child.children = [];
        }
    });

    chain.children.map((child) => {
        combineChildComposers(child);
    })
}

function mapToPublisherOrComposer(chain, callback) {
    if (chain.children) {
        async.eachSeries(chain.children, (child, ecb) => {
            async.series([
                // Top Level child
                (scb) => {
                    if (child.type === 'Publisher') {
                        child.publisherId = 'PUBID'
                        scb();
                    } else if(child.type === 'Composer') {
                        child.composerId = 'COMID'
                        scb();
                    }
                }, 
                // Children composers/publishers
                (scb) => {
                    if (child.children) {
                        mapToPublisherOrComposer(child, scb);
                    } else {
                        scb();
                    }
                }
            ], ecb)
        }, callback)
    }
}

function combineSameLevelParents(chain) {
    let combinedChildren = [];
    // Loop through children and combine any same level parents
    if(chain.children) {
        chain.children.map((child) => {
            let childAlreadyAdded = false;
            combinedChildren.map((combinedChild) => {
                if(
                    child.type === combinedChild.type && 
                    child.name === combinedChild.name && 
                    child.firstName === combinedChild.firstName && 
                    child.middleName === combinedChild.middleName && 
                    child.surname === combinedChild.surname && 
                    child.caeNumber === combinedChild.caeNumber && 
                    child.controlled === combinedChild.controlled && 
                    child.mechanicalOwnership === combinedChild.mechanicalOwnership && 
                    child.mechanicalCollection === combinedChild.mechanicalCollection && 
                    child.performanceOwnership === combinedChild.performanceOwnership && 
                    child.performanceCollection === combinedChild.performanceCollection && 
                    child.contractType === combinedChild.contractType
                ) {
                    combinedChild.children = combinedChild.children.concat(child.children);
                    childAlreadyAdded = true;
                }
            });
    
            if (!childAlreadyAdded) {
                combinedChildren.push(child);
            }
        });

        // Do the same for the children's children
        combinedChildren.map((child) => {
            child.children = combineSameLevelParents(child)
        })
    }

    return combinedChildren;
}

