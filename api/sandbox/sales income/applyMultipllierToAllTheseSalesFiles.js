require('dotenv').config();
require('../../models/db');
const async = require('async');
const SalesFile = require('../../models/salesFile');
const ObjectId = require('mongodb').ObjectId;

function applyMultiplierToSalesFiles(clientId, salesFileIds, multiplier) {
  async.eachLimit(salesFileIds, 10, (salesFileId, eachCb) => {
    SalesFile.find({ clientId, _id: ObjectId(salesFileId)}, { _id: 1 }, (findErr, salesFiles) => {
      if (findErr) {
        console.log(findErr)
        eachCb();
      } else {
        const salesFile = salesFiles[0];
        if (salesFile) {
          SalesFile.findByIdAndUpdate(salesFile._id, { $set: { 'overwriteFields.multiplier': multiplier } }, { timestamps: false }, (updateErr, salesFileUpdated) => {
            if (updateErr) {
              eachCb(updateErr);
            } else {
              console.log(`creating ingest Task for sales file ${salesFileUpdated._id}`);
              salesFileUpdated.createIngestTask(2, eachCb);
            }
          });
        } else {
          console.log(`Sales file with id ${salesFileId} not found for clientId ${clientId}`);
          eachCb();
        }
      };
    });
  }, (err) => {
    if (err) { console.error(err); }
    console.log("Complete");
    process.exit(-1);
  });
}

