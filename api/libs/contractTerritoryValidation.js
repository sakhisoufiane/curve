function checkTerritory(terms) {
  if (_.filter(terms, { territory: 'WW' }).length) {
    return true;
  }
  const codes = _.uniqBy(terms, 'territory');
  if (codes.length < territoriesCodes.length) {
    return false;
  }
  return true;
}

function checkContract(contract) {
  let verify = true;
  verify = verify && checkTerritory(contract.salesTerms);
  verify = verify && checkTerritory(contract.deductionsTerms);
  verify = verify && checkTerritory(contract.costsTerms);
  return verify;
}

