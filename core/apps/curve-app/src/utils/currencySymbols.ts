/**
 * Gets the currency symbol for a given currency code
 * @param currencyCode - The currency code (e.g., 'GBP', 'USD', 'EUR')
 * @returns The currency symbol (e.g., '£', '$', '€') or the original code if not found
 */
export const getCurrencySymbol = (currencyCode: string): string => {
  return CURRENCY_SYMBOLS[currencyCode.toUpperCase()] || currencyCode;
};

/**
 * Gets all available currency codes
 * @returns Array of all supported currency codes
 */
export const getAvailableCurrencyCodes = (): string[] => {
  return Object.keys(CURRENCY_SYMBOLS);
};

/**
 * Checks if a currency code is supported
 * @param currencyCode - The currency code to check
 * @returns True if the currency code is supported
 */
export const isCurrencySupported = (currencyCode: string): boolean => {
  return currencyCode.toUpperCase() in CURRENCY_SYMBOLS;
};
